#!/usr/bin/env python3
"""Find where each script line starts/ends in a voice-over — no AI model, just pauses + line lengths.

    python3 audio/voice_sync.py                 # analyse audio/vo/voice.mp3  -> src/vo_timing.js
    python3 audio/voice_sync.py new_voice.mp3   # copy it in as audio/vo/voice.mp3 first, then analyse

How: ffmpeg finds the pauses; dynamic programming picks the pauses that best split the speech so that each
line's share of time matches its share of characters (src/lines.js). If a recording has fewer pauses than
lines, the longest chunks are split by character share. Check the printed table; fix by hand in
src/vo_timing.js if a line is off (each entry is [start, end] in seconds of the voice file).
"""
import os, re, sys, shutil, subprocess, json
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
VO = os.path.join(HERE, 'vo', 'voice.mp3')
if len(sys.argv) > 1:
    shutil.copyfile(sys.argv[1], VO); print('voice ->', VO)
lines = re.findall(r"say: '((?:[^'\\]|\\.)*)'", open(os.path.join(ROOT, 'src', 'lines.js'), encoding='utf8').read())
chars = [len(re.sub(r"[\s.,!?—…‘’'\-।:;]", '', s)) for s in lines]; N = len(lines)
dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', VO], capture_output=True, text=True).stdout)

def speech_chunks(noise=-38, d=.22):
    out = subprocess.run(['ffmpeg', '-hide_banner', '-i', VO, '-af', f'silencedetect=noise={noise}dB:d={d}', '-f', 'null', '-'], capture_output=True, text=True).stderr
    ss = [float(x) for x in re.findall(r'silence_start: ([\d.]+)', out)]; se = [float(x) for x in re.findall(r'silence_end: ([\d.]+)', out)]
    sil = list(zip(ss, se + [dur] * (len(ss) - len(se)))); ch, t = [], 0.0
    for a, b in sil:
        if a - t > .08: ch.append([t, a])
        t = b
    if dur - t > .08: ch.append([t, dur])
    return ch

ch = speech_chunks()
while len(ch) < N:            # too few pauses: split the chunk that is longest relative to the text it must hold
    i = max(range(len(ch)), key=lambda k: ch[k][1] - ch[k][0]); a, b = ch[i]; ch[i:i + 1] = [[a, (a + b) / 2], [(a + b) / 2, b]]
K = len(ch); tot = sum(chars); sp = ch[-1][1] - ch[0][0]
INF = 1e18; best = [[INF] * (K + 1) for _ in range(N + 1)]; prv = [[0] * (K + 1) for _ in range(N + 1)]; best[0][0] = 0
for n in range(1, N + 1):          # line n-1 covers chunks j..k-1
    for k in range(n, K - (N - n) + 1):
        for j in range(n - 1, k):
            if best[n - 1][j] >= INF: continue
            d = ch[k - 1][1] - ch[j][0]; c = (d / sp - chars[n - 1] / tot) ** 2 * 1e4
            if best[n - 1][j] + c < best[n][k]: best[n][k] = best[n - 1][j] + c; prv[n][k] = j
seg, k = [], K
for n in range(N, 0, -1): j = prv[n][k]; seg.append([round(ch[j][0], 2), round(ch[k - 1][1], 2)]); k = j
seg.reverse()
print(f'{os.path.basename(VO)}: {dur:.2f}s · {K} speech chunks · {N} lines')
for i, (a, b) in enumerate(seg): print(f'{i + 1:2d}  {a:7.2f} → {b:7.2f}  ({b - a:5.2f}s)  {lines[i][:46]}')
open(os.path.join(ROOT, 'src', 'vo_timing.js'), 'w', encoding='utf8').write(
    '/* generated by audio/voice_sync.py — [start, end] of each line in audio/vo/voice.mp3 (seconds). Hand-edit if needed. */\n'
    f'const VO_TIMING = {{ file: "voice.mp3", duration: {dur:.3f}, lines: {json.dumps(seg)} }};\n')
print('-> src/vo_timing.js')
